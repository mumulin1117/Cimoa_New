import assert from 'node:assert/strict'
import path from 'node:path'
import fs from 'node:fs'
import { create_scenario } from '../../src/stores/scenarios.js'

export async function test_discover({ page, origin, evidence, check }) {
  const load = async (name = 'default', transform) => {
    const data = create_scenario(name); transform?.(data)
    await page.evaluate(data => localStorage.setItem('cimoa_app_state_v2', JSON.stringify({ type: 'object', data })), data)
    await page.goto(origin + '/#/pages/discover/index', { waitUntil: 'networkidle' })
    await page.reload({ waitUntil: 'networkidle' }); await page.locator('.discover-header').waitFor()
    return data
  }
  const storage = () => page.evaluate(() => localStorage.getItem('cimoa_app_state_v2'))
  const rect = selector => page.locator(selector).first().evaluate(el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height, bottom: r.bottom } })
  const shot = name => page.screenshot({ path: path.join(evidence, `discover-${name}.png`) })
  const photo_ready = () => page.locator('.profile-photo[data-media-status="ready"]').waitFor()
  const scroll_bottom = () => page.locator('.main-tab-scroll .uni-scroll-view-scrollbar-hidden').first().evaluate(el => { el.scrollTop = el.scrollHeight; return { top: el.scrollTop, width: el.clientWidth, scrollWidth: el.scrollWidth } })
  await load(); await photo_ready()
  assert.equal(await page.locator('.discover-name').textContent(), 'Chloe Lin, 21')
  assert.deepEqual(await page.locator('.discover-tag').allTextContents(), ['HKUST', 'Business', 'ENFP'])
  const tag_tops = await page.locator('.discover-tag').evaluateAll(tags => tags.map(tag => tag.getBoundingClientRect().top))
  assert.ok(tag_tops.every(top => Math.abs(top - tag_tops[0]) < 1), 'default tags must remain on one source row')
  assert.equal(await page.locator('.discover-photo-card').count(), 1)
  assert.equal(await page.locator('.post-card, .profile-hero, .icebreaker-card').count(), 0)
  const card = await rect('.discover-photo-card'), tool = await rect('.discover-tool'), send = await rect('.discover-send'), header = await rect('.discover-header'), bar = await rect('.tabbar')
  assert.ok(Math.abs(card.width - 353) < 1); assert.ok(Math.abs(card.height - 542) < 1)
  assert.ok(Math.abs(card.y - 76) < 1); assert.ok(Math.abs(tool.width - 54) < 1)
  assert.ok(Math.abs(send.height - 60) < 1); assert.ok(Math.abs(send.y - 688) < 1)
  assert.equal(await page.locator('.page-transition').evaluate(el => getComputedStyle(el).animationDuration), '0.26s')
  assert.equal(await page.locator('.discover-verified').count(), 1)
  assert.match(await page.locator('.profile-photo img').getAttribute('src'), /maya-full\.png/)
  assert.equal(await page.locator('.profile-photo uni-image > div').evaluate(el => getComputedStyle(el).backgroundPosition), '50% 22%')
  await shot('default')
  check('Discover source photo/card/toolbar/CTA geometry, cRise260, canonical person and exact local image', { card, tool, send, header, bar })

  const before = await storage()
  for (const [id, target] of [['photo.openMe.click.1','/pages/profile/index'], ['photo.openDiscoverFilters.click.1','/pages/auto-match/preferences'], ['photo.expand.click.1','/pages/discover/profile?user_id=user_chloe']]) {
    const entry = page.locator(`[data-interaction="${id}"]`)
    assert.equal(await entry.getAttribute('data-target'), target)
    await entry.click(); assert.match(await page.locator('.discover-error').textContent(), /not been restored/)
    assert.equal(await page.locator('.main-tab-frame').getAttribute('data-page-depth'), '1')
  }
  await page.getByRole('button', { name: 'Send shot', exact: true }).click()
  assert.match(await page.locator('.discover-error').textContent(), /already connected/)
  assert.equal(await storage(), before)
  check('profile/preferences/detail dependencies are explicit; default connected person cannot create another request or spend')

  await load('discover_unconnected'); const free_before = await storage()
  assert.equal(await page.locator('.discover-send').getAttribute('data-target'), '/pages/discover/icebreaker/select?user_id=user_chloe')
  await page.locator('.discover-send').dblclick(); assert.match(await page.locator('.discover-error').textContent(), /not been restored/)
  assert.equal(await storage(), free_before)
  await shot('dependency-error')
  check('zero-coin unconnected user gets correct icebreaker intent; repeated entry never spends or fabricates a request')

  await load('discover_unverified'); await page.locator('.discover-send').click()
  assert.match(await page.locator('.discover-error').textContent(), /verification/)
  await load('default', data => { data.users[1].discoverable = false; data.users[2].discoverable = false })
  await page.locator('.discover-send').click(); assert.match(await page.locator('.discover-error').textContent(), /already pending/)
  check('unverified viewer and existing inbound request fail with specific eligibility errors')

  await load('discover_empty'); assert.equal(await page.locator('.discover-photo-card').count(), 0)
  assert.equal(await page.locator('.discover-send').getAttribute('aria-disabled'), 'true')
  const empty_before = await storage(); await page.reload({ waitUntil: 'networkidle' }); await page.locator('.discover-empty').waitFor(); assert.equal(await storage(), empty_before)
  await shot('empty')
  check('empty state is not a fake profile, CTA disabled, refresh preserves source data')

  await load('discover_no_photo'); await page.locator('.profile-photo[data-media-status="empty"]').waitFor()
  assert.equal(await page.locator('.profile-photo image, .profile-photo img').count(), 0)
  await shot('no-photo')
  await page.route('**/static/assets/head/maya-full.png', route => route.abort())
  await load(); await page.locator('.profile-photo[data-media-status="error"]').waitFor()
  await shot('photo-error')
  await page.unroute('**/static/assets/head/maya-full.png')
  await page.getByRole('button', { name: 'Retry photo', exact: true }).click(); await photo_ready()
  assert.equal(await page.locator('.discover-error').count(), 0)
  check('no-photo and real request failure are distinct; retry loads original asset without opening profile')

  await page.clock.install()
  let held_request
  await page.route('**/static/assets/head/maya-full.png', route => { held_request = route })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.locator('.profile-photo[data-media-status="loading"]').waitFor()
  const loading_before = await storage()
  await page.clock.fastForward(11000)
  await page.locator('.profile-photo[data-media-status="error"]').waitFor()
  assert.equal(await storage(), loading_before)
  await held_request?.abort(); await page.unroute('**/static/assets/head/maya-full.png')
  await page.getByRole('button', { name: 'Home', exact: true }).click(); await page.locator('.home-title').waitFor()
  await page.clock.fastForward(11000)
  assert.equal(await page.locator('.profile-photo').count(), 0)
  await page.clock.resume()
  await load(); await photo_ready()
  check('slow photo shows loading then a retryable 10-second timeout; leaving cleans photo UI without writes')

  const media_url = 'data:text/javascript;base64,' + Buffer.from(fs.readFileSync('src/utils/mediaRepository.js', 'utf8')).toString('base64')
  const meta = await page.evaluate(async url => { const { media_repository } = await import(url); const blob = await (await fetch('/static/assets/head/maya-full.png')).blob(); await media_repository.put('discover_photo', blob); return { byte_size: blob.size, mime: blob.type } }, media_url)
  await load('default', data => { const photo = data.profile_photos.find(p => p.photo_id === data.users[1].photo_ids[0]); photo.media_url = 'indexeddb://discover_photo'; data.media_files.push({ media_id: 'discover_photo', owner_user_id: 'user_chloe', kind: 'image', media_url: photo.media_url, ...meta }) })
  await photo_ready(); assert.match(await page.locator('.profile-photo img').getAttribute('src'), /^blob:/)
  const blob_before = await storage(); await page.reload({ waitUntil: 'networkidle' }); await photo_ready(); assert.equal(await storage(), blob_before)
  assert.match(await page.locator('.profile-photo img').getAttribute('src'), /^blob:/)
  await page.getByRole('button', { name: 'Home', exact: true }).click(); await page.locator('.home-title').waitFor()
  await page.getByRole('button', { name: 'Discover', exact: true }).click(); await photo_ready()
  assert.equal(await page.locator('.main-skeleton').count(), 0)
  await page.evaluate(async url => { const { media_repository } = await import(url); await media_repository.delete('discover_photo') }, media_url)
  await page.reload({ waitUntil: 'networkidle' }); await page.locator('.profile-photo[data-media-status="error"]').waitFor()
  check('real IndexedDB photo decodes after refresh/Tab return; removed Blob reports failure, never another image')

  await load('blocked'); assert.equal(await page.locator('.discover-photo-card').getAttribute('data-user-id'), 'user_liam')
  await page.getByRole('button', { name: 'Home', exact: true }).click(); await page.locator('.home-title').waitFor(); assert.equal(await page.locator('#connection-user_chloe').count(), 0)
  await page.getByRole('button', { name: 'Discover', exact: true }).click(); assert.equal(await page.locator('.discover-photo-card').getAttribute('data-user-id'), 'user_liam')
  await load('discover_private'); assert.deepEqual(await page.locator('.discover-tag').allTextContents(), ['HKUST','ENFP'])
  await load('default', data => { data.users[1].verification_status = 'pending' }); assert.equal(await page.locator('.discover-verified').count(), 0)
  check('blocking synchronizes Home and Discover; field privacy and actual verification control displayed metadata')

  await page.evaluate(() => localStorage.setItem('cimoa_app_state_v2', '{corrupt'))
  await page.reload({ waitUntil: 'networkidle' }); await page.locator('.discover-read-error').waitFor()
  await page.getByRole('button', { name: 'Retry', exact: true }).click(); assert.equal(await storage(), '{corrupt')
  assert.equal(await page.locator('.discover-photo-card').count(), 0); await shot('read-error')
  await load('session_expired'); await page.locator('.discover-session-error').waitFor(); assert.equal(await page.locator('.discover-photo-card').count(), 0)
  check('corrupt storage retry never overwrites data; expired session does not leak profiles')

  await load('discover_long'); await photo_ready()
  assert.ok((await rect('.discover-photo-card')).height > 542)
  let scrolled = await scroll_bottom(); assert.ok(scrolled.top > 0); assert.equal(scrolled.width, scrolled.scrollWidth)
  const info = await rect('.discover-info'); assert.ok(info.bottom <= (await rect('.main-tab-scroll')).bottom + 1)
  assert.deepEqual(await rect('.discover-header'), header); assert.deepEqual(await rect('.discover-send'), send); assert.deepEqual(await rect('.tabbar'), bar)
  await shot('long')
  await page.setViewportSize({ width: 320, height: 568 }); await page.waitForTimeout(100)
  scrolled = await scroll_bottom(); assert.ok(scrolled.top > 0); assert.equal(scrolled.width, scrolled.scrollWidth)
  assert.ok((await rect('.discover-info')).bottom <= (await rect('.main-tab-scroll')).bottom + 1)
  assert.ok((await rect('.discover-send')).bottom < (await rect('.tabbar')).y)
  await shot('narrow')
  check('long name and tags remain readable; photo area scrolls on narrow screens without moving header/CTA/Tabbar')

  await page.setViewportSize({ width: 393, height: 852 }); await load(); await photo_ready()
  await page.evaluate(() => window.CommonTemplateSafeAreaBridge.update({ top: 54, bottom: 0 }))
  assert.ok(Math.abs((await rect('.discover-photo-card')).y - 130) < 1)
  assert.ok(Math.abs((await rect('.discover-tool')).y - 60) < 1)
  await shot('source-insets')
  await page.evaluate(() => window.CommonTemplateSafeAreaBridge.update({ top: 59, bottom: 34 }))
  assert.ok(Math.abs((await rect('.discover-header')).height - header.height - 59) < 1)
  assert.ok(Math.abs((await rect('.discover-send')).y - send.y + 34) < 1)
  assert.ok(Math.abs((await rect('.tabbar')).y - bar.y + 34) < 1)
  assert.equal(await page.locator('.safe-area--top').count(), 0)
  await scroll_bottom(); await shot('safe-area')
  check('header owns safe top once, Tabbar owns safe bottom once; 54/0 source geometry and 59/34 bridge tests, not native evidence')
}
